def clear_all_buckets() -> dict:
    """
    Deletes ALL objects across ALL buckets in MinIO.
    Re-initializes required buckets ('images' and 'knowledge-documents') and policies afterwards.
    """
    if not HAS_BOTO3:
        return {"status": "skipped", "reason": "boto3 not installed"}

    deleted_counts = {}
    try:
        client = _get_client()

        # Scan ALL buckets currently in MinIO
        all_b_res = client.list_buckets()
        bucket_names = [b["Name"] for b in all_b_res.get("Buckets", [])]

        # Always include active configured buckets
        for target_b in [_images_bucket(), _docs_bucket(), "images", "knowledge-documents"]:
            if target_b not in bucket_names:
                bucket_names.append(target_b)

        for bucket_name in set(bucket_names):
            count = 0
            try:
                paginator = client.get_paginator('list_objects_v2')
                for page in paginator.paginate(Bucket=bucket_name):
                    objects = page.get('Contents', [])
                    for obj in objects:
                        try:
                            client.delete_object(Bucket=bucket_name, Key=obj['Key'])
                            count += 1
                        except Exception as del_err:
                            logger.warning(f"Error deleting object '{obj['Key']}' from bucket '{bucket_name}': {del_err}")
                deleted_counts[bucket_name] = count
                logger.info(f"🗑️ Cleared {count} objects from MinIO bucket '{bucket_name}'.")
            except Exception as b_err:
                logger.warning(f"Error clearing MinIO bucket '{bucket_name}': {b_err}")
                deleted_counts[bucket_name] = count

        ensure_all_buckets()
        return {"status": "success", "deleted_counts": deleted_counts}
    except Exception as e:
        logger.error(f"clear_all_buckets failed: {e}")
        return {"status": "error", "message": str(e)}

